    /**
     * Adjusts the position and size of components when the frame is resized.
     */
    private void adjustComponentPositions() {
        int newWidth = getContentPane().getWidth();
        int newHeight = getContentPane().getHeight();

        // Título "PORTAFOLIO DE SERVICIOS"
        int titleWidth = newWidth - 100; // Mantener el ancho dinámico
        jLabel1.setBounds(50, 80, titleWidth, 40); // Mover más abajo a Y=80

        // Botón Regresar (más grande y más a la esquina)
        int regresarButtonWidth = 240; // Más grande
        int regresarButtonHeight = 65; // Más grande
        jButton1.setBounds(10, 10, regresarButtonWidth, regresarButtonHeight); // Más cerca de la esquina

        // Posicionamiento de los botones de servicio en una cuadrícula
        int buttonSize = 150; // Tamaño del área del botón (icono + texto)
        int buttonIconSize = 120; // Tamaño del icono dentro del botón
        int horizontalGap = 60; // Espacio horizontal entre botones
        int verticalGap = 40; // Espacio vertical entre filas de botones

        int totalRowWidth = (2 * buttonSize) + horizontalGap;
        int startX = (newWidth - totalRowWidth) / 2;
        int startY = jLabel1.getY() + jLabel1.getHeight() + 30; // Debajo del título, con un espacio de 30px

        // Primera fila: Internet y Televisión
        // Internet
        jButton9.setBounds(startX, startY, buttonSize, buttonSize + 30); // +30 para el texto
        jLabel6.setBounds(startX, startY + buttonSize, buttonSize, 20); // Etiqueta debajo del botón

        // Televisión
        jButton8.setBounds(startX + buttonSize + horizontalGap, startY, buttonSize, buttonSize + 30);
        jLabel5.setBounds(startX + buttonSize + horizontalGap, startY + buttonSize, buttonSize, 20);

        // Segunda fila: Telefonía Móvil y Telefonía Fija
        startY += buttonSize + 30 + verticalGap; // Mover hacia abajo para la siguiente fila
        // Telefonía Móvil
        jButton7.setBounds(startX, startY, buttonSize, buttonSize + 30);
        jLabel3.setBounds(startX, startY + buttonSize, buttonSize, 20);

        // Telefonía Fija
        jButton4.setBounds(startX + buttonSize + horizontalGap, startY, buttonSize, buttonSize + 30);
        jLabel4.setBounds(startX + buttonSize + horizontalGap, startY + buttonSize, buttonSize, 20);

        backgroundPanel.revalidate();
        backgroundPanel.repaint();
    }

