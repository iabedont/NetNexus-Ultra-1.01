    // Método auxiliar para configurar botones de servicio
    private void setupServiceButton(JButton button, String imagePath, String fallbackText) {
        try {
            ImageIcon serviceIcon = new ImageIcon(getClass().getResource(imagePath));
            if (serviceIcon.getImageLoadStatus() == MediaTracker.COMPLETE) {
                Image img = serviceIcon.getImage();
                Image scaledImg = img.getScaledInstance(120, 120, Image.SCALE_SMOOTH); // Escalar icono
                button.setIcon(new ImageIcon(scaledImg));
            } else {
                logger.log(Level.WARNING, "Imagen '{0}' no encontrada. Usando texto de marcador para el botón.", imagePath);
                button.setText(fallbackText);
            }
        } catch (Exception e) {
            logger.log(Level.WARNING, "Error al cargar la imagen '{0}': {1}", new Object[]{imagePath, e.getMessage()});
            button.setText(fallbackText);
        }
        button.setContentAreaFilled(false);
        button.setBorderPainted(false);
        button.setFocusPainted(false);
        button.setHorizontalTextPosition(SwingConstants.CENTER);
        button.setVerticalTextPosition(SwingConstants.BOTTOM);
        button.setFont(new Font("Segoe UI", Font.BOLD, 14));
        button.setForeground(new Color(30, 50, 70)); // Texto azul oscuro para botones
    }

